#!/usr/bin/env python3
"""Connect the AI governance audit file to a Wazuh single-node Docker deployment.

    python3 siem/wazuh/setup_wazuh.py --wazuh-dir ~/wazuh-docker/single-node
    python3 siem/wazuh/setup_wazuh.py --wazuh-dir ~/wazuh-docker/single-node --uninstall

Run it from anywhere, after cloning wazuh-docker (see siem/wazuh/README-wazuh.md).
It changes two things in the Wazuh folder, both reversible with --uninstall:

  1. config/wazuh_cluster/wazuh_manager.conf - appends a <localfile> block (between
     ai-governance markers) so the manager reads the audit file as JSON.
  2. docker-compose.override.yml - mounts this project's logs/ folder (read-only)
     and siem/wazuh/ai_governance_rules.xml into the manager container. Docker
     Compose merges this file automatically; Wazuh's own files are not edited.

It also checks vm.max_map_count and memory, which Wazuh's indexer needs.
"""

from __future__ import annotations

import argparse
import os
import platform
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
RULES = os.path.join(HERE, "ai_governance_rules.xml")
BEGIN, END = "<!-- ai-governance:begin -->", "<!-- ai-governance:end -->"
CONTAINER_LOG_DIR = "/var/log/ai-governance"
AUDIT_FILE_NAME = "governance-decisions.jsonl"
OVERRIDE_MARK = "# generated by ai-governance siem/wazuh/setup_wazuh.py"

LOCALFILE = f"""{BEGIN}
<ossec_config>
  <localfile>
    <log_format>json</log_format>
    <location>{CONTAINER_LOG_DIR}/{AUDIT_FILE_NAME}</location>
    <only-future-events>no</only-future-events>
  </localfile>
</ossec_config>
{END}
"""


def strip_block(text: str) -> str:
    start = text.find(BEGIN)
    if start == -1:
        return text
    end = text.find(END, start)
    end = len(text) if end == -1 else end + len(END)
    return (text[:start].rstrip("\n") + "\n" + text[end:].lstrip("\n")).rstrip("\n") + "\n"


def override_yaml(logs_dir: str) -> str:
    def q(path: str) -> str:
        return '"' + path.replace("\\", "/").replace('"', '\\"') + '"'

    return f"""{OVERRIDE_MARK}
# Remove with: python3 siem/wazuh/setup_wazuh.py --wazuh-dir <this folder> --uninstall
services:
  wazuh.manager:
    volumes:
      - {q(logs_dir + ':' + CONTAINER_LOG_DIR + ':ro')}
      - {q(RULES + ':/var/ossec/etc/rules/ai_governance_rules.xml:ro')}
"""


def check_host() -> None:
    if platform.system() == "Linux":
        try:
            value = int(open("/proc/sys/vm/max_map_count").read())
        except OSError:
            value = 0
        if value < 262144:
            print(f"  WARNING: vm.max_map_count is {value}; the Wazuh indexer needs 262144. Run:")
            print("             sudo sysctl -w vm.max_map_count=262144")
            print("             echo 'vm.max_map_count=262144' | sudo tee /etc/sysctl.d/99-wazuh-max-map-count.conf")
            print("           (With Docker Desktop the setting belongs inside its VM; see README-wazuh.md.)")
        else:
            print(f"  vm.max_map_count = {value} (ok)")
        try:
            mem_kb = int(next(l for l in open("/proc/meminfo") if l.startswith("MemTotal")).split()[1])
            gb = mem_kb / 1024 / 1024
            note = "ok" if gb >= 15 else "tight: use the 12 GB settings in README-wazuh.md"
            print(f"  memory: {gb:.1f} GB ({note})")
        except (OSError, StopIteration):
            pass


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--wazuh-dir", required=True, help="the wazuh-docker/single-node folder")
    ap.add_argument("--logs-dir", default=os.path.join(ROOT, "logs"),
                    help="folder holding governance-decisions.jsonl (default: this project's logs/)")
    ap.add_argument("--force", action="store_true", help="replace an existing docker-compose.override.yml")
    ap.add_argument("--uninstall", action="store_true")
    args = ap.parse_args()

    wdir = os.path.abspath(os.path.expanduser(args.wazuh_dir))
    conf = os.path.join(wdir, "config", "wazuh_cluster", "wazuh_manager.conf")
    compose = os.path.join(wdir, "docker-compose.yml")
    override = os.path.join(wdir, "docker-compose.override.yml")
    for path in (compose, conf):
        if not os.path.isfile(path):
            sys.exit(f"Not a wazuh-docker single-node folder (missing {path}).\n"
                     "Clone it first: git clone https://github.com/wazuh/wazuh-docker.git -b v4.14.10")

    with open(conf, encoding="utf-8") as fh:
        text = strip_block(fh.read())
    if not args.uninstall:
        text = text.rstrip("\n") + "\n\n" + LOCALFILE
    with open(conf, "w", encoding="utf-8") as fh:
        fh.write(text)
    print(f"  {'removed from' if args.uninstall else 'updated'} {conf}")

    ours = os.path.exists(override) and OVERRIDE_MARK in open(override, encoding="utf-8").read()
    if args.uninstall:
        if ours:
            os.remove(override)
            print(f"  removed {override}")
        print("Done. Apply with: docker compose up -d --force-recreate wazuh.manager  (in the Wazuh folder)")
        return 0

    if os.path.exists(override) and not ours and not args.force:
        sys.exit(f"{override} already exists and was not written by this script.\n"
                 "Merge the volumes from siem/wazuh/README-wazuh.md into it by hand, or rerun with --force.")
    logs_dir = os.path.abspath(os.path.expanduser(args.logs_dir))
    os.makedirs(logs_dir, exist_ok=True)
    with open(override, "w", encoding="utf-8") as fh:
        fh.write(override_yaml(logs_dir))
    print(f"  wrote   {override}")
    print(f"          mounts {logs_dir} -> {CONTAINER_LOG_DIR} (read-only)")
    print(f"          mounts {RULES}")
    if not os.path.exists(os.path.join(logs_dir, AUDIT_FILE_NAME)):
        print(f"  NOTE: {AUDIT_FILE_NAME} does not exist yet; start the governance server and send a request.")
    check_host()
    print("\nNext, in the Wazuh folder:  docker compose up -d   (or --force-recreate wazuh.manager if it is running)")
    print("Then verify from this project: python3 siem/wazuh/check_wazuh.py --wazuh-dir", args.wazuh_dir)
    return 0


if __name__ == "__main__":
    sys.exit(main())
