<#
  Intune Win32 app: install ai-governance hooks (machine-wide) for __AGENT__.
  Runs as SYSTEM. Generated by intune/build_intune_packages.py, version __VERSION__.

  Install command (Sysnative makes a 64-bit PowerShell run even though the
  Intune Management Extension is a 32-bit process):
    %SystemRoot%\Sysnative\WindowsPowerShell\v1.0\powershell.exe -NoProfile -ExecutionPolicy Bypass -File .\Install-AIGovernance.ps1

  Exit codes: 0 success, 1 Python not found, 2 installer failed.
#>
[CmdletBinding()]
param(
    [string]$ApiUrl = "__API_URL__",
    [string]$Token = "__TOKEN__",
    [string]$Agent = "__AGENT__",
    [string]$KiroPolicyPath = "__KIRO_POLICY_WINDOWS__",
    [string]$IdcStartUrl = "__IDC_START_URL__",
    [string]$IdcRegion = "__IDC_REGION__",
    [string]$SettingsB64 = "__SETTINGS_B64__",
    [string]$PythonPath = ""
)
$ErrorActionPreference = "Stop"
$Version = "__VERSION__"
$ProgramFiles64 = if ($env:ProgramW6432) { $env:ProgramW6432 } else { $env:ProgramFiles }
$GovDir = Join-Path $ProgramFiles64 "ai-governance"
$LauncherDir = Join-Path $env:ProgramData "ai-governance"
$LogDir = Join-Path $env:ProgramData "Microsoft\IntuneManagementExtension\Logs"
New-Item -ItemType Directory -Force -Path $LogDir | Out-Null
Start-Transcript -Path (Join-Path $LogDir "ai-governance-install.log") -Append | Out-Null

function Find-Python {
    if ($PythonPath -and (Test-Path $PythonPath)) { return $PythonPath }
    # Machine-wide installs only: a per-user Python under AppData is not reachable
    # by every user who signs in to this device.
    Get-ChildItem -Path (Join-Path $ProgramFiles64 "Python3*\python.exe") -ErrorAction SilentlyContinue |
        Sort-Object { if ($_.Directory.Name -match '^Python(\d)(\d+)$') { [int]$Matches[1] * 100 + [int]$Matches[2] } else { 0 } } -Descending |
        Select-Object -First 1 -ExpandProperty FullName
}

function Protect-Folder([string]$Path) {
    if (-not (Test-Path $Path)) { return }
    # SYSTEM and Administrators: full control. Users: read and execute only.
    & icacls $Path /inheritance:r /grant:r "*S-1-5-18:(OI)(CI)F" "*S-1-5-32-544:(OI)(CI)F" "*S-1-5-32-545:(OI)(CI)RX" | Out-Null
}

try {
    $Python = Find-Python
    if (-not $Python) {
        Write-Output "Machine-wide Python 3 not found under $ProgramFiles64\Python3*. Deploy Python first (set it as a dependency of this app)."
        Stop-Transcript | Out-Null
        exit 1
    }
    Write-Output "Using Python: $Python"

    # Windows PowerShell 5.1 drops empty-string arguments to native programs,
    # so optional arguments are added only when they have a value.
    # The token goes to the installer through an environment variable of this process
    # only, never on a command line (command lines are visible to other processes).
    $env:GOV_API_TOKEN = $Token
    $InstallArgs = @((Join-Path $PSScriptRoot "install_hooks.py"), "--agent", $Agent, "--scope", "managed",
              "--api-url", $ApiUrl, "--token-store", "file", "--python", $Python)
    if ($Agent -ne "kiro") { $InstallArgs += "--lock-hooks" }
    if ($KiroPolicyPath) { $InstallArgs += @("--kiro-policy-path", $KiroPolicyPath) }
    if ($IdcStartUrl) { $InstallArgs += @("--idc-start-url", $IdcStartUrl) }
    if ($IdcRegion) { $InstallArgs += @("--idc-region", $IdcRegion) }
    $SettingsFile = $null
    if ($SettingsB64) {
        # Extra hook settings (--set at build time), decoded to a temporary file.
        $SettingsFile = Join-Path $env:TEMP ("ai-governance-settings-" + [guid]::NewGuid() + ".env")
        [System.IO.File]::WriteAllText($SettingsFile,
            [System.Text.Encoding]::UTF8.GetString([Convert]::FromBase64String($SettingsB64)))
        $InstallArgs += @("--settings-file", $SettingsFile)
    }

    & $Python @InstallArgs
    $code = $LASTEXITCODE
    Remove-Item Env:\GOV_API_TOKEN -ErrorAction SilentlyContinue
    if ($SettingsFile) { Remove-Item $SettingsFile -ErrorAction SilentlyContinue }
    if ($code -ne 0) { throw "install_hooks.py exited with $code" }

    Protect-Folder $GovDir
    Protect-Folder $LauncherDir
    Set-Content -Path (Join-Path $GovDir "VERSION") -Value $Version -Encoding ASCII
    Write-Output "ai-governance $Version installed for $Agent."
    Stop-Transcript | Out-Null
    exit 0
}
catch {
    Write-Output "Install failed: $_"
    Stop-Transcript | Out-Null
    exit 2
}
